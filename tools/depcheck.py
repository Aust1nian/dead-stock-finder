#!/usr/bin/env python3
"""Fails if the shipped app could talk to anything but Square.

For every shipping target:
  1. No crate from DENY is anywhere in the app's shipped dependency tree:
     no telemetry, crash reporting, updater, or Tauri plugin that opens URLs.
  2. The HTTP stack (HTTP_STACK) appears only beneath dsf-square, the one
     client with the host allowlist. With dsf-square pruned from the tree,
     none of it may remain.
  3. The `sandbox` feature (Square's Sandbox host) is off in the shipped build.
  4. Every crate in the tree is listed in tools/deps-allowlist.txt, so a new
     dependency can't slip in without someone reading what it is.
  5. The page's runtime npm dependencies are only @tauri-apps/api, and the
     built page (app/dist, if present) names no outside URL and uses no
     browser networking API.

Usage: python3 tools/depcheck.py [--update-allowlist]
"""

import re
import subprocess
import sys
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ALLOWLIST = ROOT / "tools" / "deps-allowlist.txt"
APP = "dead-stock-finder"
SHIPPING_TARGETS = ["aarch64-apple-darwin", "x86_64-apple-darwin", "x86_64-pc-windows-msvc"]

DENY = {
    "reqwest", "hyper", "hyper-util", "h2", "h3", "quinn", "curl", "curl-sys", "isahc", "surf",
    "attohttpc", "minreq", "tungstenite", "tokio-tungstenite", "native-tls", "openssl", "openssl-sys",
    "sentry", "sentry-core", "opentelemetry", "tracing-opentelemetry", "rustls-platform-verifier",
    "tauri-plugin-http", "tauri-plugin-updater", "tauri-plugin-opener", "tauri-plugin-shell",
    "tauri-plugin-websocket", "tauri-plugin-upload", "tauri-plugin-deep-link", "tauri-plugin-notification",
    "tauri-plugin-log", "tauri-plugin-sql", "tauri-plugin-store",
}
# Allowed only beneath dsf-square.
HTTP_STACK = {"ureq", "ureq-proto", "rustls", "rustls-webpki", "webpki-roots", "rustls-native-certs", "ring", "socks"}

ALLOWED_NPM_RUNTIME = {"@tauri-apps/api"}
ALLOWED_URL_HOSTS = {"ipc.localhost", "tauri.localhost", "asset.localhost", "www.w3.org"}
DENY_JS = ["new WebSocket", "EventSource(", "sendBeacon", "XMLHttpRequest", "fetch("]


def tree(target: str, extra: list[str]) -> set[str]:
    out = subprocess.run(
        ["cargo", "tree", "-p", APP, "--target", target, "-e", "normal,no-proc-macro",
         "--prefix", "none", "--format", "{p}", *extra],
        cwd=ROOT, check=True, capture_output=True, text=True,
    ).stdout
    return {line.split()[0] for line in out.splitlines() if line.strip()}


def square_features(target: str) -> set[str]:
    out = subprocess.run(
        ["cargo", "tree", "-p", APP, "--target", target, "-e", "normal,features,no-proc-macro",
         "-i", "dsf-square", "--prefix", "none"],
        cwd=ROOT, capture_output=True, text=True,
    ).stdout
    return set(re.findall(r'^dsf-square feature "([^"]+)"', out, re.M))


def main() -> int:
    update = "--update-allowlist" in sys.argv
    problems: list[str] = []
    every: set[str] = set()
    for target in SHIPPING_TARGETS:
        crates = tree(target, [])
        every |= crates
        for name in sorted(crates & DENY):
            problems.append(f"{target}: {name} must not ship (network, telemetry or updater)")
        outside = tree(target, ["--prune", "dsf-square"])
        for name in sorted(outside & HTTP_STACK):
            problems.append(f"{target}: {name} reaches the app without going through dsf-square's allowlist")
        if "ureq" not in crates:
            problems.append(f"{target}: ureq missing; did the client move?")
        if "sandbox" in square_features(target):
            problems.append(f"{target}: the sandbox feature is on in the shipped build")

    names = sorted(every)
    if update:
        ALLOWLIST.write_text("# Every crate in the shipped app (all targets). Generated by\n"
                             "# tools/depcheck.py --update-allowlist; review additions.\n" + "\n".join(names) + "\n")
    else:
        listed = {l.strip() for l in ALLOWLIST.read_text().splitlines() if l.strip() and not l.startswith("#")}
        for name in names:
            if name not in listed:
                problems.append(f"new crate {name}: review it, then run tools/depcheck.py --update-allowlist")

    package = json.loads((ROOT / "app" / "package.json").read_text())
    runtime = set(package.get("dependencies", {}))
    if runtime - ALLOWED_NPM_RUNTIME:
        problems.append(f"page runtime dependencies beyond @tauri-apps/api: {sorted(runtime - ALLOWED_NPM_RUNTIME)}")

    dist = ROOT / "app" / "dist"
    if dist.exists():
        for f in dist.rglob("*"):
            if f.suffix not in {".js", ".html", ".css"}:
                continue
            text = f.read_text(errors="replace")
            for host in re.findall(r"https?://([a-zA-Z0-9.-]+)", text):
                if host not in ALLOWED_URL_HOSTS:
                    problems.append(f"{f.relative_to(ROOT)}: names {host}")
            for api in DENY_JS:
                if api in text:
                    problems.append(f"{f.relative_to(ROOT)}: uses {api}")

    for p in problems:
        print("depcheck:", p)
    if not problems:
        print(f"depcheck: ok ({len(names)} crates, {len(SHIPPING_TARGETS)} targets)")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
